import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {transform} from 'esbuild';
const scripts=['app.js','shifts.js','shifts-actions.js','pending-changes.js','records-ui.js','absence-ui.js','app-shell.js','intake-editor.js'];
const output=path.resolve(process.cwd(),'dist');
if(path.dirname(output)!==process.cwd()||path.basename(output)!=='dist')throw Error('Unexpected public output path');
await fs.rm(output,{recursive:true,force:true});
const banner='/* © 2026 PRIME POLICE · Uso reservado. */';
let html=await fs.readFile('index.html','utf8');
const inlineCss=[...html.matchAll(/<style>([\s\S]*?)<\/style>/g)].map(m=>m[1]).join('\n');
const source=(await Promise.all(scripts.map(f=>fs.readFile(f,'utf8')))).join('\n;\n');
const js=await transform(source,{minify:true,format:'iife',target:'es2022',legalComments:'none',banner,sourcemap:false});
const css=await transform(inlineCss+'\n'+await fs.readFile('admin.css','utf8')+'\n'+await fs.readFile('software.css','utf8'),{loader:'css',minify:true,target:'es2022',legalComments:'none'});
const hash=value=>createHash('sha256').update(value).digest('hex').slice(0,12);
const jsFile='app.'+hash(js.code)+'.js',cssFile='app.'+hash(css.code)+'.css';
html=html.replace(/<style>[\s\S]*?<\/style>/g,'').replace(/<link rel="stylesheet" href="(?:admin|software)\.css[^\"]*">/g,'').replace(/<script src="[^\"]+" defer><\/script>/g,'');
html=html.replace('</head>','<link rel="stylesheet" href="assets/'+cssFile+'"></head>').replace('</body>','<script src="assets/'+jsFile+'" defer></script></body>');
html=html.replace(/<!--[^]*?-->/g,'').replace(/>\s+</g,'><').trim();
await fs.mkdir('dist/assets',{recursive:true});
await Promise.all([fs.writeFile('dist/index.html',html),fs.writeFile('dist/assets/'+jsFile,js.code),fs.writeFile('dist/assets/'+cssFile,css.code),fs.copyFile('manifest.webmanifest','dist/manifest.webmanifest'),fs.copyFile('icon.svg','dist/icon.svg'),fs.writeFile('dist/.nojekyll','')]);
console.log('Public build: index, manifest, icon and two compact assets. No server files or source maps.');
console.log(JSON.stringify({javascript_bytes:Buffer.byteLength(js.code),stylesheet_bytes:Buffer.byteLength(css.code)}));
